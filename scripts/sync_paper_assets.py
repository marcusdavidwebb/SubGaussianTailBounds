#!/usr/bin/env python3
"""Refresh bibliography and the five nonlinked main-paper label snapshots."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re

LABELS = (
    "sec:barriers",
    "sec:one-row-proof",
    "sec:matrix-proof",
    "eq:spectral-bounds",
    "eq:shift-event",
)


def main() -> None:
    supplement_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--paper-root", type=Path, required=True,
                        help="existing paper checkout (build main.tex first)")
    args = parser.parse_args()
    paper_root = args.paper_root.expanduser().resolve()
    manuscript = paper_root / "main.tex"
    aux = paper_root / "build/latex/main.aux"
    bibliography = paper_root / "references.bib"
    for required in (manuscript, aux, bibliography):
        if not required.is_file():
            parser.error(f"required existing source is unavailable: {required}")
    source = aux.read_text(encoding="utf-8")
    lines = []
    for label in LABELS:
        match = re.search(r"^\\newlabel\{" + re.escape(label)
                          + r"\}\{\{([^{}]+)\}\{([^{}]+)\}", source, re.MULTILINE)
        if match is None:
            parser.error(f"missing number/page entry in main.aux: {label}")
        number, page = match.groups()
        lines.append(f"\\newlabel{{main-{label}}}{{{{{number}}}{{{page}}}{{}}{{}}{{}}}}")
    digest = hashlib.sha256(manuscript.read_bytes()).hexdigest()
    snapshot = (
        "% Main-paper numbers for standalone supplementary builds.\n"
        "% Generated by scripts/sync_paper_assets.py from the in-preparation paper.\n"
        "% main.tex SHA-256: " + digest + "\n"
        "% References use \\ref* and create no missing main.pdf links.\n"
        + "\n".join(lines) + "\n"
    )
    (supplement_root / "docs").mkdir(exist_ok=True)
    (supplement_root / "docs/main-labels.tex").write_text(snapshot, encoding="utf-8")
    (supplement_root / "references.bib").write_bytes(bibliography.read_bytes())
    print("Updated references.bib and five main-paper reference numbers.")


if __name__ == "__main__":
    main()
