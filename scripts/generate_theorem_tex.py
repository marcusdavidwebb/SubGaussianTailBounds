#!/usr/bin/env python3
"""Build TeX/PDF from the README theorem and the current root Lean statement.

Only the small Markdown subset used by the README theorem is supported; unknown
formatting fails rather than silently omitting content. This documentation check
does not establish any mathematical claim or change Lean verification policy.
"""
from __future__ import annotations

import argparse
import importlib.util
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
from urllib.parse import urljoin, urlsplit

# The update command should leave only its TeX and PDF outputs in the checkout.
sys.dont_write_bytecode = True

_spec = importlib.util.spec_from_file_location(
    "canonical_statement", Path(__file__).resolve().with_name("check_canonical_statement.py"))
canonical = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(canonical)

OUTPUT = "MainTheoremStatement.tex"
PDF_OUTPUT = "MainTheoremStatement.pdf"
CONSTANTS_PATH = Path("lean/SingularValueBounds/Canonical/Constants.lean")
REPOSITORY = "https://github.com/marcusdavidwebb/SubGaussianTailBounds"
PREAMBLE = r"""% Generated by scripts/generate_theorem_tex.py; do not edit this file directly.
% Sources: README.md (attribution and Theorem), complete canonical source.
% Refresh TeX and PDF: python3 scripts/generate_theorem_tex.py
% Check:   python3 scripts/generate_theorem_tex.py --check
% Compilation files are temporary; only the .tex and .pdf are kept.
\documentclass[11pt,a4paper]{article}
\usepackage[margin=25mm]{geometry}
\usepackage{amsmath,amssymb}
\usepackage{fontspec}
\setmonofont{DejaVuSansMono.ttf}[Scale=MatchLowercase]
\usepackage{fvextra}
\usepackage{booktabs,xcolor}
\definecolor{LinkColor}{HTML}{245572}
\DefineVerbatimEnvironment{LeanSource}{Verbatim}{fontsize=\small,
  breaklines=true,breakanywhere=true,numbers=left,numbersep=8pt}
\renewcommand{\theFancyVerbLine}{\scriptsize\arabic{FancyVerbLine}}
\usepackage[colorlinks=true,urlcolor=LinkColor,linkcolor=LinkColor]{hyperref}
\hypersetup{pdftitle={Explicit singular-value tail bounds}}
\newcommand{\gt}{>}
\setlength{\parindent}{0pt}
\setlength{\parskip}{0.45em}
\setlength{\emergencystretch}{2em}
\begin{document}
\begin{center}
{\Large Explicit singular-value tail bounds}
\end{center}

"""


def escape_text(text: str) -> str:
    replacements = {
        "\\": r"\textbackslash{}", "{": r"\{", "}": r"\}",
        "%": r"\%", "&": r"\&", "#": r"\#", "_": r"\_",
        "$": r"\$", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
    }
    return "".join(replacements.get(char, char) for char in text)


def inline(text: str) -> str:
    """Preserve inline math; convert code, bold and links without guessing syntax."""
    if "![" in text:
        raise ValueError("Markdown images are not supported in the theorem section.")
    token = re.compile(r"\$([^$\n]+)\$|`([^`\n]+)`|\*\*([^*\n]+)\*\*|\*([^*\n]+)\*|\[([^]\n]+)\]\(([^)\s]+)\)")
    result = []
    offset = 0
    for match in token.finditer(text):
        result.append(plain(text[offset:match.start()]))
        math, code, bold, italic, label, target = match.groups()
        if math is not None:
            result.append("$" + math + "$")
        elif code is not None:
            result.append(typewriter(code))
        elif bold is not None:
            result.append(r"\textbf{" + inline(bold) + "}")
        elif italic is not None:
            result.append(r"\emph{" + inline(italic) + "}")
        else:
            if urlsplit(target).scheme not in ("", "https"):
                raise ValueError(f"Unsupported link in statement: {target!r}")
            target = urljoin(REPOSITORY + "/blob/main/", target)
            if any(char in target for char in "{}\\"):
                raise ValueError(f"Unsupported link in statement: {target!r}")
            result.append(r"\href{" + escape_text(target) + "}{" + inline(label) + "}")
        offset = match.end()
    result.append(plain(text[offset:]))
    return "".join(result)


def typewriter(text: str) -> str:
    escaped = escape_text(text).replace(".", r".\allowbreak{}").replace("/", r"/\allowbreak{}")
    return r"\texttt{" + escaped + "}"


def plain(text: str) -> str:
    if re.search(r"[$`*\[\]<>_~\\]", text):
        raise ValueError(f"Unsupported Markdown in theorem text: {text!r}")
    return escape_text(text)


def readme_section(readme: str, heading: str) -> str:
    headings = list(re.finditer(r"^## " + re.escape(heading) + r"[ \t]*$", readme, re.MULTILINE))
    if len(headings) != 1:
        raise ValueError(f"README must contain exactly one '## {heading}' heading.")
    body = readme[headings[0].end():]
    end = re.search(r"^## ", body, re.MULTILINE)
    body = body[:end.start()] if end else body
    if not body.strip():
        raise ValueError(f"README {heading} section must not be empty.")
    return body.strip()


def theorem_section(readme: str) -> str:
    return readme_section(readme, "Theorem")


def markdown_to_tex(markdown: str) -> str:
    lines = markdown.splitlines()
    blocks = []
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.strip():
            index += 1
            continue
        if line in ("```math", "```lean"):
            language = line[3:]
            index += 1
            start = index
            while index < len(lines) and lines[index] != "```":
                index += 1
            if index == len(lines):
                raise ValueError(f"Unclosed {language} fence in README statement.")
            contents = "\n".join(lines[start:index])
            if language == "math":
                blocks.append("\\[\n" + contents + "\n\\]")
            else:
                blocks.append(r"\begin{Verbatim}[fontsize=\small,breaklines=true]" +
                              "\n" + contents + "\n" + r"\end{Verbatim}")
            index += 1
        elif line.startswith("### "):
            blocks.append(r"\subsection*{" + inline(line[4:]) + "}")
            index += 1
        elif line.startswith("|"):
            rows = []
            while index < len(lines) and lines[index].startswith("|"):
                row = lines[index].strip()
                if not row.endswith("|"):
                    raise ValueError("Theorem table rows must have enclosing pipes.")
                rows.append([cell.strip() for cell in row[1:-1].split("|")])
                index += 1
            if (len(rows) < 3 or any(len(row) != len(rows[0]) for row in rows)
                    or any(not re.fullmatch(r":?-{3,}:?", cell) for cell in rows[1])):
                raise ValueError("Unsupported Markdown table in README theorem.")
            table = [r"\begin{center}", r"\begin{tabular}{l" + "r" * (len(rows[0]) - 1) + "}",
                     r"\toprule", " & ".join(map(inline, rows[0])) + r" \\", r"\midrule"]
            table.extend(" & ".join(map(inline, row)) + r" \\" for row in rows[2:])
            table.extend([r"\bottomrule", r"\end{tabular}", r"\end{center}"])
            blocks.append("\n".join(table))
        else:
            paragraph = []
            while index < len(lines) and lines[index].strip():
                if re.match(r"\s*(?:[#|>]|```|~~~|[-+*] |\d+[.)] )", lines[index]):
                    raise ValueError(f"Unsupported Markdown block in theorem: {lines[index]!r}")
                paragraph.append(lines[index])
                index += 1
            blocks.append(inline(" ".join(paragraph)))
    return "\n\n".join(blocks)


def constants_table(readme: str, constants: str) -> str:
    """Fill the two documented rows from their exact Lean coefficients."""
    for regime in ("general", "unit"):
        values = []
        for field in ("Alpha", "Beta", "Gamma", "Delta"):
            matches = re.findall(r"^noncomputable abbrev " + regime + field +
                                 r" : ℝ := ([0-9]+\.[0-9]+)\s*$", constants, re.MULTILINE)
            if len(matches) != 1 or not re.fullmatch(r"[0-9]+\.[0-9]{2}", matches[0]):
                raise ValueError(f"{regime}{field} must have exactly two decimal places.")
            values.append(matches[0])
        pattern = r"^\| " + regime.capitalize() + r": [^|]+\|[^\n]*$"
        matches = list(re.finditer(pattern, readme, re.MULTILINE))
        if len(matches) != 1:
            raise ValueError(f"README must contain one {regime} constants row.")
        label = matches[0].group().split("|", 2)[1].strip()
        row = "| " + label + " | " + " | ".join(values) + " |"
        readme = readme[:matches[0].start()] + row + readme[matches[0].end():]
    return readme


def render_document(source: str, readme: str) -> bytes:
    """Render captured inputs without re-reading files during generation."""
    if not source.endswith("\n"):
        source += "\n"
    intro = readme.split("\n\n", 2)[1]
    theorem = theorem_section(readme)
    document = (PREAMBLE + "\n" +
                r"{\small " + markdown_to_tex(intro) + "\\par}\n" +
                r"\href{" + REPOSITORY + "}{repository}\n\n" +
                "\\section*{Theorem}\n" + markdown_to_tex(theorem) + "\n\n" +
                "\\clearpage\n\\section*{Lean statement}\n" +
                r"The complete authoritative source, \href{" + REPOSITORY + "/blob/main/" + canonical.CANONICAL_NAME +
                "}{" + canonical.CANONICAL_NAME + "}, is reproduced below. " +
                "These definitions state the propositions; " +
                r"proofs are in \href{" + REPOSITORY + "/blob/main/lean/SingularValueBounds/Canonical/Results.lean}" +
                "{Canonical/Results.lean}.\n\n" +
                "\\begin{LeanSource}[firstnumber=1]\n" + source +
                "\\end{LeanSource}\n\\end{document}\n")
    return document.encode("utf-8")


def render(root: Path) -> bytes:
    source = canonical.canonical_bytes(root).decode("utf-8")
    readme = (root / "README.md").read_text(encoding="utf-8")
    constants = (root / CONSTANTS_PATH).read_text(encoding="utf-8")
    return render_document(source, constants_table(readme, constants))


def compile_pdf(source: bytes) -> bytes:
    """Build away from the checkout; remove auxiliary files even if TeX fails."""
    engine = shutil.which("xelatex")
    if engine is None:
        raise ValueError("XeLaTeX is required to update the TeX and PDF; xelatex was not found on PATH.")
    with tempfile.TemporaryDirectory(prefix="subgaussian-theorem-") as directory:
        work = Path(directory)
        (work / OUTPUT).write_bytes(source)
        # The second pass resolves PDF page labels and other cross references.
        for _ in range(2):
            result = subprocess.run(
                [engine, "-interaction=nonstopmode", "-halt-on-error", "-no-shell-escape", OUTPUT],
                cwd=work, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
            if result.returncode:
                raise ValueError("XeLaTeX failed; existing TeX/PDF were preserved.\n" + result.stdout[-6000:])
        pdf = work / PDF_OUTPUT
        if not pdf.is_file() or not pdf.read_bytes().startswith(b"%PDF-"):
            raise ValueError("XeLaTeX did not produce a PDF; existing TeX/PDF were preserved.")
        return pdf.read_bytes()


def generate(root: Path, *, check: bool = False) -> None:
    source = canonical.canonical_bytes(root)
    readme_path = root / "README.md"
    if readme_path.is_symlink() or not readme_path.is_file():
        raise ValueError("README.md must be a regular file.")
    current_readme = readme_path.read_bytes()
    constants_path = root / CONSTANTS_PATH
    constants = constants_path.read_bytes()
    inputs = {root / canonical.CANONICAL_NAME: source,
              readme_path: current_readme, constants_path: constants}
    updated_readme = constants_table(canonical.readme_presentation(current_readme, source)
                                    .decode("utf-8"), constants.decode("utf-8")).encode("utf-8")
    expected = render_document(source.decode("utf-8"), updated_readme.decode("utf-8"))
    output = root / OUTPUT
    pdf = root / PDF_OUTPUT
    for path in (output, pdf):
        if path.is_symlink() or (path.exists() and not path.is_file()):
            raise ValueError(f"{path.name} must be a regular file, not a symlink or directory.")
    if check:
        if updated_readme != current_readme:
            raise ValueError("README Lean statement or constants differ from the Lean sources; "
                             "run python3 scripts/generate_theorem_tex.py.")
        if not output.is_file() or output.read_bytes() != expected:
            raise ValueError(
                f"{OUTPUT} is missing or out of sync; run python3 scripts/generate_theorem_tex.py.")
    else:
        built_pdf = compile_pdf(expected)
        for path, original in inputs.items():
            if path.is_symlink() or path.read_bytes() != original:
                raise ValueError(f"{path.name} changed during generation; no generated files were written.")
        if updated_readme != current_readme:
            readme_path.write_bytes(updated_readme)
        output.write_bytes(expected)
        pdf.write_bytes(built_pdf)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument("--check", action="store_true", help="Check README and TeX synchronization without writing files.")
    args = parser.parse_args()
    try:
        generate(args.root.resolve(), check=args.check)
    except (OSError, ValueError) as exc:
        raise SystemExit(f"Theorem TeX check failed: {exc}") from exc
    if args.check:
        print(f"PASS: synchronized README.md and {OUTPUT}.")
    else:
        print(f"Generated {OUTPUT} and {PDF_OUTPUT}; compilation files removed.")


if __name__ == "__main__":
    main()
