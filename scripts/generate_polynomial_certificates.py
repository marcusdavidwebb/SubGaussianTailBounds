#!/usr/bin/env python3
"""Reproduce compact polynomial witnesses using exact rational arithmetic.

The corner table and the proved polynomial coefficient identities are the inputs.
No intermediate transform matrices are retained. Lean checks the coefficient
identities, affine weights and all Bernstein signs; this script is not an oracle.
"""
from __future__ import annotations

import argparse
import ast
from fractions import Fraction as Q
from math import lcm
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CERT = ROOT / 'lean/SingularValueBounds/KL/Certificates'
UPPER = ROOT / 'lean/SingularValueBounds/KL/Upper'


def rational(expr: str, values=()) -> Q:
    """Interpret only exact arithmetic, and indexed coefficient parameters."""
    expr = re.sub(r'\bd (\d)', r'd[\1]', expr).strip()

    def go(node):
        if isinstance(node, ast.Constant) and isinstance(node.value, int):
            return Q(node.value)
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.USub):
            return -go(node.operand)
        if isinstance(node, ast.Name) and node.id == 'J':
            return values[0]
        if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name) and node.value.id == 'd':
            return values[node.slice.value]
        if isinstance(node, ast.BinOp):
            a, b = go(node.left), go(node.right)
            if isinstance(node.op, ast.Add): return a + b
            if isinstance(node.op, ast.Sub): return a - b
            if isinstance(node.op, ast.Mult): return a * b
            if isinstance(node.op, ast.Div): return a / b
        raise ValueError(f'Unsupported rational expression: {expr}')

    return go(ast.parse(expr, mode='eval').body)


def qstr(q: Q) -> str:
    return f'({q.numerator}/{q.denominator})'


def coefficient_rows(text: str, choice: int, values: list[Q], prefix="endpointMeanPolynomialCoefficients") -> list[list[Q]]:
    section = text.split(f'def {prefix}{choice} ', 1)[1].split('\ntheorem ', 1)[0]
    rows = re.findall(r'!\[([^\[\]]+)\]', section)
    return [[rational(entry, values) for entry in row.split(',')] for row in rows]


def integer_matrix(name: str, rows: list[list[int]]) -> str:
    m, n = len(rows), len(rows[0])
    entries = ',\n    '.join('![' + ', '.join(map(str, row)) + ']' for row in rows)
    return (f'  let {name} : Fin {n} → Fin {m} → ℤ :=\n'
            f'    fun k l => (integer_matrix![{entries}]) l k\n')


def affine_weights(name: str, degree: int, lo: Q, hi: Q) -> tuple[str, int]:
    den = lcm(lo.denominator, hi.denominator)
    base, width = int(lo * den), int((hi - lo) * den)
    text = (f'  let {name} : Fin {degree+1} → Fin {degree+1} → ℤ :=\n'
            f'    fun i k => ({base}:ℤ)^(k.val-i.val)*(Nat.fast_choose k.val i.val : ℤ)*'
            f'({width}:ℤ)^i.val*({den}:ℤ)^({degree}-k.val)\n')
    return text, den ** degree


def endpoint_files() -> dict[Path, str]:
    data = (UPPER / 'EndpointMeanData.lean').read_text()
    points_text = data.split('noncomputable def endpointMeanAPoint ', 1)[1].split('noncomputable def endpointMeanCornerData', 1)[0]
    points = {int(i): rational(value) for i, value in re.findall(r'\| (\d+) => ([^\n]+)', points_text)}
    points[42] = Q(1)
    corners = []
    pattern = r'\| (\d+),(\d+) => \(\(\(([^)]+)\),\(([^)]+)\),\(([^)]+)\),\(([^)]+)\)\),(\d+),(\d+)\)'
    for ki, ai, *fields in re.findall(pattern, data):
        corners.append((int(ki), int(ai), list(map(rational, fields[:4])), int(fields[4])))
    if len(corners) != 837:
        raise ValueError(f'Expected the actual 837 corner records, found {len(corners)}')
    identity = (CERT / 'EndpointMeanPolynomialIdentity.lean').read_text()
    result = {}
    for ki in range(60):
        source = '''import SingularValueBounds.KL.Certificates.EndpointMeanPolynomialIdentity
import SingularValueBounds.KL.Certificates.IntegerCoefficientStages

/-! Generated by scripts/generate_polynomial_certificates.py. Only the integer
polynomial coefficients are witnesses; the affine and Bernstein stages are computed. -/
open Polynomial
open scoped BigOperators
namespace SingularValueBounds.KL.Certificates
set_option Elab.async false
set_option maxHeartbeats 0
set_option maxRecDepth 20000

'''
        indices, dimensions = [], []
        for row, ai, corner, choice in corners:
            if row != ki: continue
            indices.append(ai)
            bottom, top = Q(ki+20, 80), Q(ki+21, 80)
            left, right = max(points[ai], bottom ** 3), points[ai+1]
            ac = (corner[1] - corner[0]) / (right-left)
            kc = (corner[2] - corner[0]) / (top-bottom)
            cross = (corner[3]-corner[2]-corner[1]+corner[0])/((right-left)*(top-bottom))
            d = [corner[0]-ac*left-kc*bottom+cross*left*bottom,
                 ac-cross*bottom, kc-cross*left, cross]
            n, m = (4, 1) if choice == 3 else (6, 15)
            dimensions.append((n, m))
            source += (f'private theorem endpoint_mean_box_{ki}_{ai} :\n'
                       f'    BoxCertificate (endpointMeanTestQ {ki} {ai}) {n} {m} (endpointMeanBox {ki} {ai}) := by\n'
                       f'  have hd : endpointBilinearCoefficients {ki} {ai} = ![{", ".join(map(qstr,d))}] := by decide +kernel\n'
                       f'  have hh : endpointMeanChoice {ki} {ai} = {choice} := by rfl\n'
                       f'  have hb : endpointMeanBox {ki} {ai} = ⟨{qstr(left)}, {qstr(right)}, {qstr(bottom)}, {qstr(top)}⟩ := by\n'
                       f'    norm_num [endpointMeanBox, endpointMeanAPoint, Fin.coe_ofNat_eq_mod]\n'
                       f'  rw [endpointMeanTestQ_eq, hd, hh, hb, endpointMeanPolynomial_identity_{choice}]\n')
            if choice == 3:
                source += '  apply boxCertificate_of_computedTensorStages 4 1\n'
                source += '  all_goals decide +kernel\n\n'
            else:
                coefficients = coefficient_rows(identity, choice, d)
                scale = lcm(*(q.denominator for line in coefficients for q in line))
                integers = [[int(q*scale) for q in line] for line in coefficients]
                source += integer_matrix('aa', integers)
                wx, dx = affine_weights('wx', n, left, right)
                wy, dy = affine_weights('wy', m, bottom, top)
                source += wx + wy
                source += f'  apply boxCertificate_of_computedIntegerStages_6_15 _ _ aa wx wy {scale} {dx} {dy}\n'
                source += '  all_goals try simp only [Fin.sum_univ_succ, Fin.sum_univ_zero, add_zero, Nat.choose_eq_fast_choose]\n'
                source += '  all_goals decide +kernel\n\n'
        source += (f'private theorem endpointMeanPolynomialActiveIndices{ki:02d} : ∀ ai : Fin 42, endpointMeanActive {ki} ai → ai ∈\n'
                   f'    ([{", ".join(map(str,indices))}] : List (Fin 42)) := by\n'
                   '  simp only [endpointMeanActive]\n  decide +kernel\n\n'
                   f'theorem endpointMeanPolynomial_row{ki:02d} (ai : Fin 42) :\n'
                   f'    endpointMeanActive {ki} ai → ∃ n m, BoxCertificate (endpointMeanTestQ {ki} ai) n m (endpointMeanBox {ki} ai) := by\n'
                   '  intro hactive\n'
                   f'  have hi := endpointMeanPolynomialActiveIndices{ki:02d} ai hactive\n'
                   '  fin_cases hi\n')
        source += ''.join(f'  · exact ⟨{n}, {m}, endpoint_mean_box_{ki}_{ai}⟩\n' for ai,(n,m) in zip(indices, dimensions))
        source += '\nend SingularValueBounds.KL.Certificates\n'
        result[CERT / f'ConcreteEndpointMeanPolynomials/Row{ki:02d}.lean'] = source
    grouped = {}
    for block in range(10):
        rows = [result[CERT / f'ConcreteEndpointMeanPolynomials/Row{i:02d}.lean']
                for i in range(6*block, 6*(block+1))]
        header = rows[0].split('private theorem ', 1)[0]
        bodies = [row[row.index('private theorem '):row.rindex('\nend SingularValueBounds.KL.Certificates')]
                  for row in rows]
        grouped[CERT / f'ConcreteEndpointMeanPolynomials/Block{block:02d}.lean'] = (
            header + '\n'.join(bodies) + '\nend SingularValueBounds.KL.Certificates\n')
    return grouped


def general_files() -> dict[Path, str]:
    data = (UPPER / 'GeneralMeanCellData.lean').read_text().split('noncomputable def generalMeanRows ', 1)[0]
    pattern = '⟨' + ', '.join([r'\(([^)]+)\)'] * 8) + r', ⟨(\d),by decide⟩⟩'
    records = re.findall(pattern, data)
    if len(records) != 1330:
        raise ValueError(f'Expected the actual 1330 general records, found {len(records)}')
    identity = (CERT / 'GeneralMeanPolynomialIdentity.lean').read_text()
    majorant_text = (UPPER / 'CertificateData.lean').read_text().split('def majorantBoxes ',1)[1].split('def majorantDegrees',1)[0]
    majorants = [list(map(rational, fields)) for fields in re.findall(r'⟨\(([^)]+)\), \(([^)]+)\), \(([^)]+)\), \(([^)]+)\)⟩',majorant_text)]
    result = {}
    for block in range(19):
        source = """import SingularValueBounds.KL.Certificates.GeneralMeanPolynomialIdentity
import SingularValueBounds.KL.Certificates.IntegerCoefficientStages8
import SingularValueBounds.KL.Certificates.ConcreteGeneralMeanGeometry

/-! Generated by scripts/generate_polynomial_certificates.py from the actual
rational cells and polynomial identities. All finite signs are checked in Lean. -/
open Polynomial
open scoped BigOperators
namespace SingularValueBounds.KL.Certificates
set_option Elab.async false
set_option maxHeartbeats 0
set_option maxRecDepth 10000

"""
        for index in range(70*block,70*(block+1)):
            fields = records[index]
            bottom,top,left,right,J,_,_,_ = map(rational,fields[:8])
            choice = int(fields[8])
            box = f'⟨{qstr(left)}, {qstr(right)}, {qstr(bottom)}, {qstr(top)}⟩'
            n,m = (8,15) if choice == 5 else (6,15) if choice < 6 else (4,0)
            polynomial = (f'(generalMeanJointCleared {qstr(J)} {choice})' if choice < 6 else
                          f'(C (C {qstr(J)}-generalMeanNormQ ({671 if choice == 6 else 563}/100)))')
            target = f'BoxCertificate {polynomial} {n} {m} {box}'
            source += (f'private theorem mean_box_{index} : {target} := by\n'
                       f'  rw [generalMeanPolynomial_identity_{choice}]\n')
            if choice >= 6:
                source += '  apply boxCertificate_of_computedTensorStages 4 0\n'
                source += '  all_goals decide +kernel\n\n'
            else:
                coefficients = coefficient_rows(identity,choice,[J],'generalMeanCoefficients')
                scale = lcm(*(q.denominator for line in coefficients for q in line))
                source += integer_matrix('aa',[[int(q*scale) for q in line] for line in coefficients])
                wx,dx = affine_weights('wx',n,left,right)
                wy,dy = affine_weights('wy',m,bottom,top)
                source += wx+wy
                source += f'  apply boxCertificate_of_computedIntegerStages_{n}_15 _ _ aa wx wy {scale} {dx} {dy}\n'
                source += '  all_goals try simp only [Fin.sum_univ_succ, Fin.sum_univ_zero, add_zero, Nat.choose_eq_fast_choose]\n'
                source += '  all_goals decide +kernel\n\n'
            source += (f'theorem generalMeanRowConditions_{index} : GeneralMeanRowConditions (generalMeanRows {index}) := by\n'
                       f'  have hd := generalMeanRows_domains {index}\n'
                       '  refine ⟨hd.1, hd.2.1, hd.2.2.1, hd.2.2.2.1, hd.2.2.2.2, ?_⟩\n')
            if choice < 6:
                ml,mr,_,mt = majorants[choice]
                source += (f'  change ({qstr(ml)} : ℚ) ≤ {qstr(left)} ∧ {qstr(right)} ≤ {qstr(mr)} ∧\n'
                           f'    {qstr(top)} ≤ {qstr(mt)} ∧ {target}\n'
                           f'  exact ⟨by norm_num, by norm_num, by norm_num, mean_box_{index}⟩\n\n')
            else:
                source += (f'  change (({choice}=6 ∧ (5/6 : ℚ) ≤ {qstr(left)}) ∨ ({choice}=7 ∧ (37/40 : ℚ) ≤ {qstr(bottom)})) ∧\n'
                           f'    {target}\n'
                           f'  exact ⟨by norm_num, mean_box_{index}⟩\n\n')
        source += (f'theorem generalMeanRowBlockConditions_{block} (j : Fin 70) :\n'
                   f'    GeneralMeanRowConditions (generalMeanRowBlocks {block} j) := by\n'
                   '  revert j\n'
                   f'  exact Fin.cases (motive := fun j => GeneralMeanRowConditions (generalMeanRowBlocks {block} j))\n'
                   f'    generalMeanRowConditions_{70*block} <|\n')
        source += ''.join(f'    Fin.cases generalMeanRowConditions_{i} <|\n' for i in range(70*block+1,70*(block+1)))
        source += '    fun j => Fin.elim0 j\n\nend SingularValueBounds.KL.Certificates\n'
        result[CERT / f'ConcreteGeneralMeanRows/Block{block:02d}.lean'] = source
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = endpoint_files() | general_files()
    obsolete = list((CERT / 'ConcreteEndpointMeanPolynomials').glob('Row*.lean'))
    if args.check and obsolete:
        raise SystemExit('Obsolete endpoint row modules remain; regenerate certificates.')
    if not args.check:
        for path in obsolete:
            path.unlink()
    for path, content in files.items():
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Stale generated certificate: {path.relative_to(ROOT)}')
        else:
            path.write_text(content)
    print(f'{"Checked" if args.check else "Generated"} {len(files)} compact polynomial modules.')


if __name__ == '__main__':
    main()
