#!/usr/bin/env python3
"""Exact finite certificates for the P11 lower determinant interface.

This checks rational polynomial identities and signs only. The Lean results
retain these facts as explicit finite premises. It supplies no analytic oracle.
"""
if not __debug__:
    raise SystemExit('Run without -O: exact assertions are required.')
import importlib.util
import hashlib
from fractions import Fraction as F
from math import factorial
from pathlib import Path
import sys
sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('poly_interface', HERE/'check_polynomial_interface.py')
poly = importlib.util.module_from_spec(spec)
spec.loader.exec_module(poly)
CASES = [
 (F(1207,1000),F(6,5),F(1631,1000),F(26,25),F(17,10),F(147,200)),
 (F(1207,1000),F(1211,1000),F(167,100),F(26,25),F(17,10),F(147,200)),
 (F(6,5),F(74,55),F(27,16),F(21,20),F(19,10),F(1)),
]
def polynomials(row):
    u,A,v,w,c,stop = row
    d={(0,0):F(1),(1,0):-u,(2,0):-u*A,(3,0):u*c}
    psi={(1,0):u,(2,0):2*v,(4,0):-2*w}
    t={(0,0):F(1)}
    exp=t
    for j in range(1,25):
        t=poly.scale(poly.mul(t,psi),F(1,j))
        exp=poly.add(exp,t)
    numerator=poly.add(poly.mul(d,exp),{(0,0):F(-1)})
    assert all(k>=2 for k,l in numerator)
    q={(k-2,l):a for (k,l),a in numerator.items()}
    assert poly.mul({(2,0):F(1)},q)==numerator
    return d,psi,q

def rat(q): return f'({q.numerator}/{q.denominator})'

def verify():
    lines=['-- Generated by check_lower_interface.py; numerical hypotheses remain explicit.',
           'import SingularValueBounds.KL.Certificates.Polynomial',
           'namespace SingularValueBounds.KL.LowerCertificates',
           'open SingularValueBounds.KL.Certificates',
           'def plateauRows : List (ℚ × ℚ × ℚ × ℚ × ℚ × ℚ) := [',
           ',\n'.join('  ('+', '.join(map(rat,row))+')' for row in CASES),']']
    counts=[]
    for i,row in enumerate(CASES):
        u,A,v,w,c,stop=row
        assert 0<u and 0<=w<=v and 0<stop<=1
        d,psi,q=polynomials(row)
        qp=poly.binary_certificate(q,F(0),stop)
        dp=poly.binary_certificate(poly.add(d,{(0,0):F(-1,10**6)}),F(0),stop)
        lines.extend([f'def plateauQTree{i} : BinaryTree := {qp[0]}',
                      f'def plateauDTree{i} : BinaryTree := {dp[0]}'])
        counts.append((qp[1],dp[1]))
    lines.append('end SingularValueBounds.KL.LowerCertificates')
    expected='\n'.join(lines)+'\n'
    target=HERE/'SingularValueBounds/KL/Lower/CertificateTrees.lean'
    if '--write' in sys.argv:
        target.write_text(expected)
    assert target.read_text()==expected,'Lean lower certificate transcription differs; inspect and regenerate.'
    print('P11 plateau Taylor/Bernstein certificates: 3 rows, leaf counts',counts)

def rounded_up(x):
    return F(-((-x.numerator*10**12)//x.denominator),10**12)
def rounded_down(x):
    return F((x.numerator*10**12)//x.denominator,10**12)
def exp_low(x,n=24):
    return sum((x**j/F(factorial(j)) for j in range(n+1)),F(0))
def exp_upper(x,n=40):
    assert 0<=x<n+2
    return exp_low(x,n)+x**(n+1)/F(factorial(n+1))/(1-x/F(n+2))
def log_upper(x):
    assert x>=1
    z=(x-1)/(x+1)
    value=2*sum((z**(2*j+1)/F(2*j+1) for j in range(24)),F(0))
    value+=2*z**49/(49*(1-z*z))
    return rounded_up(value)
def profile(k):
    return min(F(4137,1000),max(F(3,2),F(57,40)+F(23,10)*k+F(47,20)*k*k-F(3,10)*k**3))
def power_for(j):
    mid=F(2*j+1,2000)
    return F(37,10)+F(13,10)/mid-mid**2/2 if j<650 else 12-10*mid

# Independent source comparison against the original checker was recorded on
# 2026-10-20. This digest pins that transcription; it is provenance, not a
# proof that a compiler exported the same finite values.
CELL_DATA_SHA256 = "6749b1931b452c38b27a2757636ef398b4b7d3ef49c7ae744e831b6af10c095f"

def verify_moment_cells():
    assert hashlib.sha256((HERE/'SingularValueBounds/KL/Lower/CellData.lean').read_bytes()).hexdigest() == CELL_DATA_SHA256, 'CellData transcription changed; review the correspondence before repinning.'

    margins=[]
    for a,b,p in [(F(j,1000),F(j+1,1000),power_for(j)) for j in range(30,711)]+[(F(3,100),F(3,100),F(50))]:
        assert 0<a<=b<=F(711,1000) and p>=F(19,4)
        ulo,uhi=4*p/((p-1)*profile(b)),4*p/((p-1)*profile(a))
        assert uhi*b<1
        partial=sum((2*(ulo*a)**r/(r*(r+1)) for r in range(2,61)),F(0))
        assert partial>a*a  # strict, so the cubic signs have no limiting equality case
        D=1+2*p*a*a-4*a**4
        ell=rounded_up(log_upper(D)/(2*a*a))
        assert ell>0
        if ell>=8:
            V=ell
        else:
            E=exp_upper(ell)
            v=rounded_down(1/E)
            assert 0<=v<1 and v*E<=1
            V=ell-sum((v**r/r for r in range(1,7)),F(0))
        B=2*b*b+1/(p-2*b*b)
        entropy=(p-1)*(log_upper(1/(1-uhi*b))-uhi*b)/(2*b*b)+V+p*log_upper(p*B)+1/(exp_low(p-F(1,20))-1)
        assert entropy<3*p
        margins.append(3*p-entropy)
    print('P11 higher-moment certificates: 681 closed cells and small-shape cell; every finite premise passed')
    return min(margins)

if __name__=='__main__':
    verify()
    verify_moment_cells()
