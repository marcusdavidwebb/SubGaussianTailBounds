#!/usr/bin/env python3
"""Exact P19 entropy/rectangle data, using the printed fixed-point algorithm.

The original checker remains the arithmetic authority. This adapter reruns its
50 interval and 837 rectangle comparisons, captures the actual corner bounds
and selected polynomial, and checks/emits the corresponding Lean table.
"""
if not __debug__:
    raise SystemExit("Run without -O: exact assertions are required.")

from pathlib import Path
import inspect
import hashlib
import sys
sys.dont_write_bytecode = True

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import check_main_constants as printed
from check_general_mean_entropy import exp_upper, log_bounds
from check_polynomial_interface import transformed, coefficients, verify_expansion


# Reviewed-source drift guards only. These hashes are not compiler exports
# and do not replace the bounded arithmetic and coefficient checks below.
REVIEWED_SOURCES = {'EndpointMeanFinite.lean': '36f1456ef289173d224295e820c174613bc09fb0b29b42e86d6711a389732189', 'EndpointRoundedEval.lean': '4026ae5f05391be6dd04cfd67fcad751811a92528f9e417e48889021c6133adf', 'RoundedAlgorithm.lean': '965fecbd4b946155e21810afb307690e7d2565bd82cad6bf4b0d1e8bb4ee0dcd'}

def check_reviewed_sources():
    for name,expected in REVIEWED_SOURCES.items():
        actual=hashlib.sha256((HERE/'SingularValueBounds/KL/Upper'/name).read_bytes()).hexdigest()
        assert actual==expected, f'Review the finite source/interface correspondence before updating {name} provenance.'


def verify_tensor(p,al,ah,kl,kh):
    assert all(a<=8 and k<=16 for a,k in p)
    q=transformed(p,al,ah,kl,kh)
    bs=coefficients(q,8,16)
    assert min(map(min,bs))>0
    verify_expansion(q,8,16,bs)


def replace_once(source, old, new):
    assert source.count(old)==1, f"Primary checker adapter locator changed: {old!r}"
    return source.replace(old,new)


def obtain():
    source = inspect.getsource(printed.check_k_one_upper_entropy)
    source = replace_once(source, 'def check_k_one_upper_entropy():',
        'def capture():\n    records=[]; small=[]')
    source = replace_once(source, 'assert d1-bound>F(1,500)',
        'assert d1-bound>F(1,500)\n     small.append((c,bound,d1))')
    source = replace_once(source, 'count+=1',
        'records.append((kl,kh,al,ah,*Ds,c,result[1]))\n     count+=1')
    source = replace_once(source, '    def expi(z):', '''    old_logi=logi
    def logi(n,d=1):
     result=old_logi(n,d)
     assert tuple(F(v,S) for v in result)==log_bounds(F(n,d))
     return result
    def expi(z):''')
    source = replace_once(source, '    logs=[(0,0)]', '''    old_expi=expi
    def expi(z):
     result=old_expi(z)
     assert F(result,S)==exp_upper(F(z,S))
     return result
    logs=[(0,0)]''')
    source = replace_once(source, 'qi=max(90,min(200,oi,ci,spect));idx=qi-90',
        '''qi=max(90,min(200,oi,ci,spect));idx=qi-90
      assert 90<=qi<=200 and qi*hn*hn<100*hd*hd
      assert j*hn*(qi-100)*W.denominator<=200*hd*100*W.numerator''')
    source = replace_once(source, 'if bb>0:return best',
        'if bb>0:\n       verify_tensor(P,al,ah,kl,kh)\n       return best')
    source = replace_once(source,
        'for j in range(END+1):v=ceildiv(v*base,S);arr.append(v)',
        'for j in range(END+1):\n      previous=v;v=ceildiv(v*base,S);assert previous*base<=v*S;arr.append(v)')
    source = replace_once(source,
        'if j<=mj:p=min(p,ceildiv(A*exps[qi][j],S))',
        'rounded=ceildiv(A*exps[qi][j],S)\n       assert A*exps[qi][j]<=rounded*S\n       if j<=mj:p=min(p,rounded)')
    source += '\n    return records,small\n'
    env = dict(printed.__dict__)
    env.update(exp_upper=exp_upper,log_bounds=log_bounds,verify_tensor=verify_tensor)
    exec(source, env)
    return env['capture']()


def rat(x):
    return str(x.numerator) if x.denominator == 1 else f'({x.numerator}/{x.denominator})'


def lean_text(records, small):
    F = printed.F
    apoints = sorted(set([F(i,40) for i in range(41)]+[F(37,50),F(5,6)]))
    assert all(apoints[i]<apoints[i+1] for i in range(42))
    assert all(F(1,4)**3!=x for x in apoints[1:])
    assert all(d1+F(13,12)-F(1,80)<=F(58,25) for _,_,d1 in small)
    assert all(0<=al and 0<kl<kh<=1 and 0<c<=40 for kl,kh,al,ah,*_,c,choice in records)
    out = ['import SingularValueBounds.KL.Upper.RoundedAlgorithmSoundness',
           'import SingularValueBounds.KL.Upper.CertificateData', '',
           '/-! Actual 837 endpoint entropy corners and selected determinant tests.',
           'Generated by check_upper_mean_interface.py from the printed checker. -/',
           'namespace SingularValueBounds.KL.Certificates', '',
           'set_option maxHeartbeats 10000000', '',
           'def endpointMeanAPoint (i : Fin 43) : ℚ :=', '  match i.val with']
    out += [f'  | {j} => {rat(x)}' for j,x in enumerate(apoints[:-1])]
    out += ['  | _ => 1', '',
            'def endpointMeanCornerData (ki ai : ℕ) : (ℚ × ℚ × ℚ × ℚ) × Fin 7 × ℕ :=',
            '  match ki,ai with']
    for kl,kh,al,ah,d0,d1,d2,d3,c,choice in records:
        ki = int(kl*80)-20
        ai = apoints.index(ah)-1
        assert max(apoints[ai],kl**3)==al
        out.append(f'  | {ki},{ai} => (({rat(d0)},{rat(d1)},{rat(d2)},{rat(d3)}),{choice},{int(c*200)})')
    out += ['  | _,_ => ((0,0,0,0),0,1)', '',
            'def endpointSmallCutoff (i : Fin 50) : ℕ :=', '  match i.val with']
    out += [f'  | {j} => {int(c*200)}' for j,(c,_,_) in enumerate(small[:-1])]
    out += [f'  | _ => {int(small[-1][0]*200)}', '',
            'end SingularValueBounds.KL.Certificates', '']
    assert len(records)==837 and len(small)==50
    return '\n'.join(out)


def main():
    check_reviewed_sources()
    records,small=obtain()
    output=HERE/'SingularValueBounds/KL/Upper/EndpointMeanData.lean'
    expected=lean_text(records,small)
    if '--write' in sys.argv:
        output.write_text(expected)
    else:
        assert output.read_text()==expected, 'Lean endpoint entropy data differ from checker'
    print('PASS: actual P19 data; all 50 small cells and 837 joint corner/selected polynomial tests.')


if __name__=='__main__':
    main()
