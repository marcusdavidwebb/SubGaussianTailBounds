def tensor(poly,al,ah,kl,kh,na,nr):
 trans={}
 for (a,r),v in poly.items():
  for i in range(a+1):
   for j in range(r+1):trans[i,j]=trans.get((i,j),F(0))+v*comb(a,i)*al**(a-i)*(ah-al)**i*comb(r,j)*kl**(r-j)*(kh-kl)**j
 coeff={(i,j):sum(v*F(comb(i,a),comb(na,a))*F(comb(j,r),comb(nr,r)) for(a,r),v in trans.items() if a<=i and r<=j) for i in range(na+1) for j in range(nr+1)}
 # Reconstruct every coefficient of the transformed polynomial, not just its signs.
 rec={}
 for (i,j),v in coeff.items():
  for aa in range(i,na+1):
   for rr in range(j,nr+1):rec[aa,rr]=rec.get((aa,rr),F(0))+v*comb(na,i)*comb(na-i,aa-i)*(-1)**(aa-i)*comb(nr,j)*comb(nr-j,rr-j)*(-1)**(rr-j)
 assert all(rec.get(key,F(0))==trans.get(key,F(0)) for key in set(rec)|set(trans))
 assert min(coeff.values())>0
 return len(coeff)
